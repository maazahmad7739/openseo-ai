def _live_collections(token):
    out = []
    for path, kind in (("custom_collections.json?limit=250", "custom"),
                       ("smart_collections.json?limit=250", "smart")):
        url = f"https://{DOMAIN}/admin/api/2024-10/{path}"
        req = urllib.request.Request(url)
        req.add_header("X-Shopify-Access-Token", token)
        with urllib.request.urlopen(req, timeout=60) as resp:
            body = json.loads(resp.read().decode("utf-8"))
        key = "custom_collections" if kind == "custom" else "smart_collections"
        for item in body.get(key, []) or []:
            handle = item.get("handle")
            out.append({
                "collection_id": str(item.get("id")), "title": item.get("title"),
                "handle": handle, "collection_type": kind,
                "published": item.get("published_at") is not None,
                "url": canonicalize_url(f"https://{DOMAIN}/collections/{handle}"),
            })
    return out


def resolve_catalogue(offline):
    token = os.environ.get("SHOPIFY_ACCESS_TOKEN") or os.environ.get("SEED_SHOPIFY_TOKEN")
    if token and not offline:
        try:
            from connectors.shopify import get_shopify_adapter
            adapter = get_shopify_adapter(config={
                "shopify.mode": "live", "shopify.domain": SHOP_HANDLE,
                "shopify.access_token": token,
            })
            products = adapter.fetch("products", {})
            if products.get("ok"):
                collections = _live_collections(token)
                print(f"[catalogue] LIVE: {len(products['data'])} products, "
                      f"{len(collections)} collections")
                return CatalogueAdapter(products["data"], collections)
            print(f"[catalogue] live fetch failed ({products.get('error')}); "
                  "falling back to embedded snapshot")
        except Exception as exc:
            print(f"[catalogue] live fetch failed ({exc}); falling back to embedded snapshot")
    else:
        print("[catalogue] no Shopify token (--offline or unset); using embedded snapshot")
    return CatalogueAdapter(offline_products(), OFFLINE_COLLECTIONS)


