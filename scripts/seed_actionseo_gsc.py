def seed_clusters(conn, site_id):
    created = 0
    with conn.cursor() as cur:
        for spec in CLUSTERS:
            cur.execute(
                "SELECT cluster_id FROM keyword_clusters "
                "WHERE site_id = %s AND primary_keyword = %s",
                (str(site_id), spec["primary"]),
            )
            row = cur.fetchone()
            if row:
                cluster_id = row[0]
            else:
                cur.execute(
                    "INSERT INTO keyword_clusters (site_id, primary_keyword, keywords, "
                    "intent, commercial_intent, recommended_page_type, search_volume, "
                    "commercial_value) VALUES (%s, %s, %s, 'commercial', true, 'collection', "
                    "%s, %s) RETURNING cluster_id",
                    (str(site_id), spec["primary"], spec["keywords"],
                     spec["volume"], spec["commercial_value"]),
                )
                cluster_id = cur.fetchone()[0]
                created += 1
            for kw in spec["keywords"]:
                cur.execute(
                    "INSERT INTO cluster_queries (cluster_id, query) VALUES (%s, %s) "
                    "ON CONFLICT (cluster_id, query) DO NOTHING",
                    (str(cluster_id), kw),
                )
    return created


