class CatalogueAdapter:
    """Minimal adapter contract (fetch) serving pre-normalized catalogue rows."""

    def __init__(self, products, collections):
        self._data = {"products": products, "collections": collections}

    def fetch(self, capability, params):
        if capability in self._data:
            return {"ok": True, "data": self._data[capability]}
        return {"ok": False, "capability": capability, "error": "unsupported_capability"}


