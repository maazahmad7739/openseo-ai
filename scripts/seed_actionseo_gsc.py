def _base_position(pair, d, ref):
    if pair["pattern"] == "rank_decline":
        if d >= ref - timedelta(days=7):
            return 8.6
        return pair["pos_base"]
    delta = (d - (ref - timedelta(days=WINDOW_DAYS))).days
    return pair["pos_base"] + 0.4 * math.sin(delta / 3.0)


def _base_ctr(pos):
    return min(0.30, CTR_CURVE_K / (max(pos, 1.0) ** CTR_CURVE_EXP))


def seed_search_performance(conn, site_id, ref_date):
    ref = ref_date
    start = ref - timedelta(days=WINDOW_DAYS)
    rows = []
    for pair in GSC_PAIRS:
        page_url = canonicalize_url(f"https://{DOMAIN}{pair['path']}")
        devices = pair.get("devices") or list(DEVICES)
        for device in devices:
            rng = random.Random(f"{DOMAIN}|{pair['query']}|{page_url}|{device}")
            for offset in range(WINDOW_DAYS + 1):
                d = start + timedelta(days=offset)
                weekday = d.weekday()
                wd = 0.85 if weekday >= 5 else 1.0
                share = MOBILE_SHARE if device == "MOBILE" else (1.0 - MOBILE_SHARE)
                impressions = max(1, round(
                    pair["base_impressions"] * share * wd
                    * (1 + rng.uniform(-0.15, 0.15))))
                pos = _base_position(pair, d, ref)
                if device == "MOBILE":
                    pos += 0.2
                if pair["pattern"] == "low_ctr":
                    ctr = rng.uniform(0.010, 0.016)
                else:
                    ctr = min(0.30, CTR_CURVE_K / (max(pos, 1.0) ** CTR_CURVE_EXP))
                    if device == "MOBILE":
                        ctr *= 0.85
                    else:
                        ctr *= 1.10
                    if pair["pattern"] == "click_decline" and d >= ref - timedelta(days=7):
                        ctr *= 0.42
                    ctr *= (1 + rng.uniform(-0.10, 0.10))
                clicks = min(impressions, round(impressions * ctr))
                stored_ctr = round(clicks / impressions, 4) if impressions else 0
                rows.append({
                    "site_id": str(site_id), "date": str(d), "query": pair["query"],
                    "page_url": page_url, "country": "USA", "device": device,
                    "clicks": clicks, "impressions": impressions,
                    "ctr": stored_ctr, "position": round(max(1.0, pos + rng.uniform(-0.3, 0.3)), 2),
                })
    return database.insert_rows(
        conn, "search_performance", rows,
        conflict_target="site_id, date, query, page_url_hash, country, device",
        update_keys=["clicks", "impressions", "ctr", "position"],
    )


def seed_serp_snapshots(conn, site_id, ref_date):
    with conn.cursor() as cur:
        cur.execute(
            "SELECT cluster_id, primary_keyword FROM keyword_clusters WHERE site_id = %s",
            (str(site_id),),
        )
        cluster_by_primary = {pk: cid for cid, pk in cur.fetchall()}
    inserted = 0
    self_row = ("https://action-seo-test.myshopify.com/products/the-complete-snowboard", 7)
    with conn.cursor() as cur:
        for primary, competitors in COMPETITORS.items():
            cluster_id = cluster_by_primary.get(primary)
            if cluster_id is None:
                continue
            for url, position in competitors:
                cur.execute(
                    "INSERT INTO openseo_serp_snapshots (site_id, cluster_id, query, "
                    "result_url, result_domain, position, is_self, snapshot_date) "
                    "VALUES (%s, %s, %s, %s, %s, %s, false, %s) "
                    "ON CONFLICT (site_id, query, result_url, snapshot_date) DO NOTHING",
                    (str(site_id), str(cluster_id), primary, url,
                     url.split("/")[2] if "://" in url else None, position, str(ref_date)),
                )
                inserted += cur.rowcount
        cluster_id = cluster_by_primary.get("complete snowboard")
        if cluster_id is not None:
            url, position = ("https://action-seo-test.myshopify.com/products/the-complete-snowboard", 7)
            cur.execute(
                "INSERT INTO openseo_serp_snapshots (site_id, cluster_id, query, "
                "result_url, result_domain, position, is_self, snapshot_date) "
                "VALUES (%s, %s, %s, %s, %s, %s, true, %s) "
                "ON CONFLICT (site_id, query, result_url, snapshot_date) DO NOTHING",
                (str(site_id), str(cluster_id), "complete snowboard", url,
                 "action-seo-test.myshopify.com", position, str(ref_date)),
            )
            inserted += cur.rowcount
    return inserted


def verify(conn, site_id):
    out = {}
    with conn.cursor() as cur:
        for table in ("pages", "keyword_clusters", "catalogue_coverage",
                      "page_query_match_scores", "openseo_serp_snapshots",
                      "search_performance", "recommendations", "candidate_runs"):
            cur.execute(
                f"SELECT count(*) FROM {table} WHERE site_id = %s",
                (str(site_id),),
            )
            out[f"count_{table}"] = cur.fetchone()[0]
        cur.execute(
            "SELECT count(*) FROM cluster_queries cq "
            "JOIN keyword_clusters kc ON kc.cluster_id = cq.cluster_id "
            "WHERE kc.site_id = %s",
            (str(site_id),),
        )
        out["count_cluster_queries"] = cur.fetchone()[0]
        cur.execute(
            "SELECT page_type, count(*) FROM pages WHERE site_id = %s GROUP BY page_type",
            (str(site_id),),
        )
        out["pages_by_type"] = {r[0]: r[1] for r in cur.fetchall()}
        cur.execute(
            "SELECT count(*) FROM search_performance sp "
            "LEFT JOIN pages p ON p.site_id = sp.site_id AND p.url_hash = sp.page_url_hash "
            "WHERE sp.site_id = %s AND p.page_id IS NULL",
            (str(site_id),),
        )
        out["sp_rows_without_matching_page"] = cur.fetchone()[0]
        cur.execute(
            "SELECT min(date), max(date) FROM search_performance WHERE site_id = %s",
            (str(site_id),),
        )
        out["sp_date_range"] = [str(v) for v in cur.fetchone()]
        cur.execute(
            "SELECT r.generator, r.status, count(*) FROM recommendations r "
            "WHERE r.site_id = %s GROUP BY r.generator, r.status ORDER BY r.generator",
            (str(site_id),),
        )
        out["recommendations_by_generator_status"] = [
            {"generator": r[0], "status": r[1], "count": r[2]} for r in cur.fetchall()]
        cur.execute(
            "SELECT generator, action_type, COALESCE(target_url, proposed_url), "
            "COALESCE(kc.primary_keyword, ''), impact "
            "FROM recommendations r LEFT JOIN keyword_clusters kc "
            "ON kc.cluster_id = r.cluster_id "
            "WHERE r.site_id = %s AND r.status = 'raw' ORDER BY generator",
            (str(site_id),),
        )
        out["raw_candidates"] = [
            {"generator": r[0], "action_type": r[1], "url": r[2],
             "cluster": r[3], "impact": r[4]} for r in cur.fetchall()]
        cur.execute(
            "SELECT generator, candidate_count FROM candidate_runs WHERE site_id = %s "
            "ORDER BY run_at",
            (str(site_id),),
        )
        out["candidate_runs"] = [{"generator": r[0], "candidate_count": r[1]}
                                 for r in cur.fetchall()]
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-date", default="2026-09-10")
    parser.add_argument("--skip-agent", action="store_true")
    parser.add_argument("--offline", action="store_true",
                        help="skip live Shopify fetch; use embedded catalogue snapshot")
    args = parser.parse_args()
    ref_date = date.fromisoformat(args.reference_date)

    conn = database.get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("SET TIME ZONE 'UTC'")
            cur.execute(
                "SELECT site_id FROM site_config WHERE domain = %s", (DOMAIN,))
            row = cur.fetchone()
            if row:
                site_id = row[0]
                print(f"[site] existing site_id: {site_id}")
            else:
                cur.execute(
                    "INSERT INTO site_config (site_name, domain, gsc_property, "
                    "shopify_domain, catalogue_size_tier) "
                    "VALUES (%s, %s, %s, %s, 'small') RETURNING site_id",
                    (SITE_NAME, DOMAIN, f"sc-domain:{DOMAIN}", SHOP_HANDLE),
                )
                site_id = cur.fetchone()[0]
                print(f"[site] created site_id: {site_id}")
        conn.commit()

        catalogue = resolve_catalogue(args.offline)
        counts = {"pages": sync_pages_from_shopify(conn, catalogue, site_id, DOMAIN)}
        print(f"[pages] upserted: {counts['pages']}")

        counts["keyword_clusters_created"] = seed_clusters(conn, site_id)
        counts["search_performance_rows"] = seed_search_performance(conn, site_id, ref_date)
        counts["serp_snapshots"] = seed_serp_snapshots(conn, site_id, ref_date)
        conn.commit()
        print(f"[seed] clusters(+{counts['keyword_clusters_created']}), "
              f"search_performance({counts['search_performance_rows']}), "
              f"serp(+{counts['serp_snapshots']})")

        counts["catalogue_coverage"] = sync_catalogue_coverage(
            conn, site_id, DOMAIN, catalogue)
        counts["page_query_match_scores"] = sync_page_query_match_scores(conn, site_id)
        conn.commit()
        print(f"[pipeline] catalogue_coverage={counts['catalogue_coverage']}, "
              f"page_query_match_scores={counts['page_query_match_scores']}")

        gen_counts = run_candidate_generation(
            site_id, conn=conn, reference_date=args.reference_date)
        print(f"[generators] {json.dumps(gen_counts, default=str)}")

        if not args.skip_agent:
            try:
                from agents.seo_agent import run_agent
                summary = run_agent(str(site_id), conn=conn)
                print(f"[agent] {json.dumps(summary, default=str)[:800]}")
            except Exception as exc:
                conn.rollback()
                print(f"[agent] skipped after error: {type(exc).__name__}: {exc}")

        report = verify(conn, site_id)
        report["site_id"] = str(site_id)
        report["reference_date"] = args.reference_date
        report["sync_counts"] = {k: v for k, v in counts.items()}
        print("\n=== GATE 1 REPORT ===")
        print(json.dumps(report, indent=2, default=str))
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    main()